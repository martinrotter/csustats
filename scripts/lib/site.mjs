import { readFile } from 'node:fs/promises';
import { resolveProject } from './project.mjs';
import { bundleApplication, bundleWorker } from './bundle.mjs';
import { verifyVendor } from './vendor.mjs';

export function replaceToken(html, token, content, type = 'script') {
  const expression = new RegExp(`<!--\\s*${token}\\s*-->`, 'g');
  if ([...html.matchAll(expression)].length !== 1)
    throw new Error(`Expected one ${token} placeholder.`);
  const ending = type === 'style' ? /<\/style/gi : /<\/script/gi;
  const safe = content.replace(ending, type === 'style' ? '<\\/style' : '<\\/script');
  return html.replace(expression, () => safe);
}

export async function renderSite() {
  const manifest = await verifyVendor();
  const read = (file) => readFile(resolveProject(file), 'utf8');
  const [app, worker, template, license, notices] = await Promise.all([
    bundleApplication(),
    bundleWorker(),
    read('src/template.html'),
    read('LICENSE'),
    read('THIRD_PARTY_NOTICES.md'),
  ]);
  const licenseTexts = [license, notices];
  for (const dependency of manifest.packages) {
    for (const file of dependency.files.filter((entry) => entry.license)) {
      licenseTexts.push(`${file.path}\n\n${await read(file.path)}`);
    }
  }
  const content = {
    VENDOR_CSS: ['vendor/tabulator/tabulator.min.css', 'style'],
    APP_CSS: ['src/styles/base.css', 'style'],
    DATA_UI_CSS: ['src/styles/data-ui.css', 'style'],
    PAPA: ['vendor/papaparse/papaparse.min.js', 'script'],
    ECHARTS: ['vendor/echarts/echarts.min.js', 'script'],
    TABULATOR: ['vendor/tabulator/tabulator.min.js', 'script'],
    REGIONS: ['src/data/regions.json', 'script'],
  };
  let html = template;
  for (const [token, [file, type]] of Object.entries(content))
    html = replaceToken(html, token, await read(file), type);
  html = replaceToken(html, 'WORKER', worker);
  html = replaceToken(html, 'APP', app);
  html = replaceToken(html, 'LICENSES', licenseTexts.join('\n\n'));
  return '<!-- Generated by npm run build. Edit src/, not docs/index.html. -->\n' + html;
}
